import assert from 'node:assert/strict';
import fs from 'node:fs';
import { webcrypto } from 'node:crypto';
globalThis.crypto ??= webcrypto;
import { createGame, getState, dispatch } from '../shared/state.js';
import { stableStringify } from '../shared/integrity.js';
import { authorizePeerAction } from '../shared/permissions.js';
import { reduceDeterministic } from '../shared/reducer.js';
import { cloudActionPayload, cloudCommitHash, verifyCloudSignedPayload, sameCloudAction } from '../shared/cloud-action.js';

const enc=new TextEncoder();
const pair=await crypto.subtle.generateKey({name:'ECDSA',namedCurve:'P-256'},true,['sign','verify']);
const publicJwk=await crypto.subtle.exportKey('jwk',pair.publicKey);
const digest=await crypto.subtle.digest('SHA-256',enc.encode(stableStringify(publicJwk)));
const fingerprint=[...new Uint8Array(digest)].map(b=>b.toString(16).padStart(2,'0')).join('');
createGame({gameName:'Sequencer Test',creatorName:'Creator'});
let state=getState();
const creatorId=Object.values(state.players).find(p=>p.roles.includes('creator')).id;
dispatch({type:'PLAYER_IDENTITY_BOUND',actorId:creatorId,playerId:creatorId,identityFingerprint:fingerprint,identityPublicKey:publicJwk});
state=getState();
const submittedAction={type:'GAME_RENAMED',name:'Cloud Ordered Democracy'};
const payload=cloudActionPayload({roomCode:'ABC234',playerId:creatorId,action:submittedAction,expectedStateVersion:state.stateVersion,nonce:'nonce-12345678'});
const sig=await crypto.subtle.sign({name:'ECDSA',hash:'SHA-256'},pair.privateKey,enc.encode(stableStringify(payload)));
const signature=Buffer.from(sig).toString('base64');
assert.equal(await verifyCloudSignedPayload(publicJwk,payload,signature),true);
assert.equal(await verifyCloudSignedPayload(publicJwk,{...payload,roomCode:'XYZ234'},signature),false);
const applied=authorizePeerAction(state,submittedAction,creatorId);
assert.equal(applied.actorId,creatorId);
const reduced=reduceDeterministic(state,applied,{seed:'transition-seed-1',timestamp:1_800_000_000_000});
assert.equal(reduced.state.meta.name,'Cloud Ordered Democracy');
assert.equal(reduced.state.stateVersion,state.stateVersion+1);
const commit={sequence:1,previousCommitHash:null,playerId:creatorId,nonce:payload.nonce,expectedStateVersion:state.stateVersion,acceptedAt:1_800_000_000_000,transitionSeed:'transition-seed-1',stateVersion:reduced.state.stateVersion,stateHash:reduced.stateHash,submittedAction,appliedAction:applied,signature};
commit.commitHash=cloudCommitHash(commit);
assert.equal(cloudCommitHash(commit),commit.commitHash);
assert.equal(sameCloudAction(authorizePeerAction(state,submittedAction,creatorId),commit.appliedAction),true);
assert.notEqual(cloudCommitHash({...commit,stateHash:'0'.repeat(64)}),commit.commitHash);

const worker=fs.readFileSync(new URL('../worker/src/index.js',import.meta.url),'utf8');
const client=fs.readFileSync(new URL('../js/cloud-network.js',import.meta.url),'utf8');
assert.match(worker,/CREATE TABLE IF NOT EXISTS commits/);
assert.match(worker,/CREATE TABLE IF NOT EXISTS used_nonces/);
assert.match(worker,/verifyCloudSignedPayload/);
assert.match(worker,/authorizePeerAction/);
assert.match(worker,/reduceDeterministic/);
assert.match(worker,/Stale state version/);
assert.match(worker,/This signed request nonce has already been used/);
assert.match(client,/ACTION_COMMITTED/);
assert.match(client,/Cloud state divergence detected/);
assert.match(client,/submitCloudAction/);
assert.match(client,/RESYNC_REQUEST/);
console.log('Phase 40 signed canonical Cloud action sequencer: PASS');
