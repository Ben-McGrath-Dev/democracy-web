import assert from 'node:assert/strict';
import { webcrypto } from 'node:crypto';
globalThis.crypto ??= webcrypto;
import { stableStringify } from '../shared/integrity.js';
import { cloudAuthPayload, cloudPublicKeyFingerprint, verifyCloudAuthSignature, challengeExpired } from '../shared/cloud-auth.js';
import { CLOUD_MESSAGE } from '../shared/protocol.js';
const enc=new TextEncoder();
const pair=await crypto.subtle.generateKey({name:'ECDSA',namedCurve:'P-256'},true,['sign','verify']);
const pub=await crypto.subtle.exportKey('jwk',pair.publicKey);
const challenge={roomCode:'ABC234',challengeId:'challenge-1',nonce:'deadbeef',issuedAt:1000,expiresAt:61000};
const payload=cloudAuthPayload(challenge);
const sig=await crypto.subtle.sign({name:'ECDSA',hash:'SHA-256'},pair.privateKey,enc.encode(stableStringify(payload)));
const b64=Buffer.from(sig).toString('base64');
assert.equal(await verifyCloudAuthSignature(pub,payload,b64),true);
assert.equal(await verifyCloudAuthSignature(pub,{...payload,roomCode:'XYZ234'},b64),false);
assert.equal((await cloudPublicKeyFingerprint(pub)).length,64);
assert.equal(challengeExpired(challenge,60000),false);
assert.equal(challengeExpired(challenge,62000),true);
assert.equal(CLOUD_MESSAGE.AUTH_OK,'AUTH_OK');
const worker=await import('node:fs/promises').then(fs=>fs.readFile(new URL('../worker/src/index.js',import.meta.url),'utf8'));
assert.match(worker,/cloudAuthPayload/);
assert.match(worker,/verifyCloudAuthSignature/);
assert.match(worker,/challengeExpired/);
assert.match(worker,/const role = player \? \(player\.roles\?\.includes\('creator'\) \? 'creator' : 'player'\) : 'unregistered'/);
assert.match(worker,/authentication_required/);
console.log('Phase 38 cryptographic authentication: PASS');
