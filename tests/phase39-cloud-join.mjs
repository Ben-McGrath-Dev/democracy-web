const fp='a'.repeat(64);
assert.equal(cloudPlayerIdForFingerprint(fp), `player_cloud_${'a'.repeat(24)}`);
assert.throws(()=>cloudPlayerIdForFingerprint('bad'),/valid identity fingerprint/);
